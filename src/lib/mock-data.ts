export function getToolBySlug(slug: string): AITool | undefined {
  return tools.find((tool) => tool.slug === slug);
}

export function getFeaturedTools(): AITool[] {
  return tools.filter((tool) => tool.featured);
}

export function getToolsBySlugs(slugs: string[]): AITool[] {
  return slugs
    .map((slug) => getToolBySlug(slug))
    .filter((tool): tool is AITool => Boolean(tool));
}

export function getAlternativeTools(tool: AITool): AITool[] {
  return getToolsBySlugs(tool.alternatives);
}
